using System.Text.Json;

namespace RelaxKonOS.ManagedRuntimes;

public sealed record SingBoxBuildEvidence(string Version, string Os, string Architecture, IReadOnlySet<string> Tags, bool Cgo);

/// <summary>sing-box-specific version/tag syntax. Build evidence is not installation or interoperability evidence.</summary>
public static class SingBoxNativeValidation
{
    public static bool TryTag(string? tag, out RuntimeSemanticVersion version) =>
        RuntimeSemanticVersion.TryParse(tag is { Length: > 0 } && tag[0] == 'v' ? tag[1..] : tag, out version);

    public static SingBoxBuildEvidence Parse(string output, string expectedTag, string expectedOs, string expectedArchitecture)
    {
        if (output.Length > 8192 || output.Any(c => char.IsControl(c) && c is not ('\r' or '\n'))
            || !TryTag(expectedTag, out var expected)) throw new RuntimePolicyException("runtime.native_version_invalid");
        var lines = output.Split('\n').Select(line => line.EndsWith('\r') ? line[..^1] : line).ToArray();
        if (lines.Length == 0 || !lines[0].StartsWith("sing-box version ", StringComparison.Ordinal)
            || !RuntimeSemanticVersion.TryParse(lines[0][17..], out var measured) || measured.Normalized != expected.Normalized)
            throw new RuntimePolicyException("runtime.native_version_mismatch");
        var fields = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var line in lines.Skip(1).Where(line => line.Length != 0))
        {
            var colon = line.IndexOf(": ", StringComparison.Ordinal);
            if (colon < 0 || !fields.TryAdd(line[..colon], line[(colon + 2)..])
                || line[..colon] is not ("Environment" or "Tags" or "Revision" or "CGO"))
                throw new RuntimePolicyException("runtime.native_version_invalid");
        }
        if (!fields.TryGetValue("Environment", out var environment) || !fields.TryGetValue("CGO", out var cgo)
            || cgo is not ("enabled" or "disabled")) throw new RuntimePolicyException("runtime.native_version_invalid");
        var parts = environment.Split(' ');
        if (parts.Length != 2 || !parts[0].StartsWith("go", StringComparison.Ordinal) || parts[0].Length < 3
            || parts[1] != expectedOs + "/" + expectedArchitecture)
            throw new RuntimePolicyException("runtime.native_platform_mismatch");
        var tags = new HashSet<string>(StringComparer.Ordinal);
        if (fields.TryGetValue("Tags", out var buildTags))
            foreach (var tag in buildTags.Split(','))
                if (tag.Length == 0 || tag.Length > 128 || !tag.All(c => char.IsAsciiLetterOrDigit(c) || c == '_') || !tags.Add(tag))
                    throw new RuntimePolicyException("runtime.native_features_invalid");
        if (fields.TryGetValue("Revision", out var revision) && (revision.Length is < 7 or > 64 || !revision.All(Uri.IsHexDigit)))
            throw new RuntimePolicyException("runtime.native_version_invalid");
        return new(measured.Normalized, expectedOs, expectedArchitecture, tags, cgo == "enabled");
    }

    /// <summary>Reads the one current native format generated by SingBoxConfiguration; native 'check' remains mandatory.</summary>
    public static void RequireConfigurationFeatures(SingBoxBuildEvidence build, ReadOnlyMemory<byte> nativeConfiguration)
    {
        if (nativeConfiguration.Length > 4 * 1024 * 1024) throw new RuntimePolicyException("runtime.native_configuration_invalid");
        try
        {
            using var document = JsonDocument.Parse(nativeConfiguration, new() { MaxDepth = 64 });
            if (!document.RootElement.TryGetProperty("inbounds", out var inbounds) || inbounds.ValueKind != JsonValueKind.Array)
                throw new RuntimePolicyException("runtime.native_configuration_invalid");
            foreach (var inbound in inbounds.EnumerateArray())
            {
                if (inbound.GetProperty("type").GetString() == "hysteria2" && !build.Tags.Contains("with_quic"))
                    throw new RuntimePolicyException("runtime.native_feature_missing");
                if (inbound.TryGetProperty("tls", out var tls) && tls.TryGetProperty("reality", out var reality)
                    && reality.TryGetProperty("enabled", out var enabled) && enabled.GetBoolean() && !build.Tags.Contains("with_utls"))
                    throw new RuntimePolicyException("runtime.native_feature_missing");
            }
        }
        catch (Exception ex) when (ex is JsonException or InvalidOperationException or KeyNotFoundException)
        { throw new RuntimePolicyException("runtime.native_configuration_invalid"); }
    }
}
