using System.IO.Compression;
using System.Text;
using RelaxKonOS.Protocol.ApplicationDeployments;

namespace RelaxKonOS.Server.ApplicationDeployments;

/// <summary>
/// Bounded, traversal-safe archive extraction for a deployment build context. Only declared files
/// are materialized: no links, no absolute paths, no parent traversal, and both the declared and the
/// observed expanded size are enforced so an archive cannot lie its way past the limit.
/// </summary>
public static class ApplicationArchiveExtractor
{
    public static async Task<string?> WriteDockerfileAsync(string destination, ApplicationSourceKind kind, string baseImage, int port,
        string entry, bool selfContained, CancellationToken cancellationToken)
    {
        if (kind is ApplicationSourceKind.JavaJar or ApplicationSourceKind.PythonProject
            && await ApplicationPayload.PrepareAsync(destination, kind, entry, cancellationToken) is { } problem)
            return problem;
        var dockerfile = ApplicationDockerfile.Generate(kind, baseImage, port, entry, selfContained);
        // The build must include the validated payload regardless of the archive's .dockerignore.
        var encoding = new UTF8Encoding(false);
        await File.WriteAllTextAsync(Path.Combine(destination, ".dockerignore"),
            "# Generated by RelaxKonOS; the complete validated payload is required.\n", encoding, cancellationToken);
        await File.WriteAllTextAsync(Path.Combine(destination, "Dockerfile"), dockerfile, encoding, cancellationToken);
        return null;
    }

    public static async Task<string?> PrepareAsync(Stream archive, string destination, int maximumEntries, long maximumExpandedBytes, int maximumPathDepth, CancellationToken cancellationToken)
    {
        Directory.CreateDirectory(destination);
        var root = Path.GetFullPath(destination);
        using var zip = OpenArchive(archive);
        if (zip is null) return ApplicationDeploymentProblemCodes.ArchiveUnavailable;
        if (zip.Entries.Count > maximumEntries)
            return ApplicationDeploymentProblemCodes.ArchiveTooManyEntries;

        long declared = 0;
        long observed = 0;
        var buffer = new byte[81920];
        foreach (var entry in zip.Entries)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var relative = Normalize(entry.FullName, maximumPathDepth);
            if (relative is null)
                return ApplicationDeploymentProblemCodes.ArchiveUnsafeEntry;
            if (relative.Length == 0) continue;
            if (IsLink(entry))
                return ApplicationDeploymentProblemCodes.ArchiveUnsafeEntry;

            var target = Path.GetFullPath(Path.Combine(root, relative));
            if (!PathSafety.IsWithin(root, target))
                return ApplicationDeploymentProblemCodes.ArchiveUnsafeEntry;

            if (entry.FullName.EndsWith('/') || entry.FullName.EndsWith('\\'))
            {
                Directory.CreateDirectory(target);
                continue;
            }

            declared += entry.Length;
            if (declared > maximumExpandedBytes)
                return ApplicationDeploymentProblemCodes.ArchiveExpandedTooLarge;

            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            await using var source = entry.Open();
            await using var destinationStream = new FileStream(target, FileMode.Create, FileAccess.Write, FileShare.None, buffer.Length, FileOptions.Asynchronous);
            int read;
            while ((read = await source.ReadAsync(buffer, cancellationToken)) > 0)
            {
                observed += read;
                if (observed > maximumExpandedBytes)
                    return ApplicationDeploymentProblemCodes.ArchiveExpandedTooLarge;
                await destinationStream.WriteAsync(buffer.AsMemory(0, read), cancellationToken);
            }
        }

        UnwrapPublishRoot(root, cancellationToken);
        return null;
    }

    private static void UnwrapPublishRoot(string root, CancellationToken cancellationToken)
    {
        var directories = Directory.GetDirectories(root);
        if (directories.Length != 1 || Directory.EnumerateFiles(root).Any()) return;

        // Docker reads the extraction directory as its build context. The generated Dockerfile
        // needs context-relative paths even when the archive wraps the application in a directory.
        var wrapper = directories[0];
        foreach (var entry in Directory.EnumerateFileSystemEntries(wrapper))
        {
            cancellationToken.ThrowIfCancellationRequested();
            var destination = Path.Combine(root, Path.GetFileName(entry));
            if (Directory.Exists(entry)) Directory.Move(entry, destination);
            else File.Move(entry, destination);
        }
        Directory.Delete(wrapper);
    }

    private static ZipArchive? OpenArchive(Stream archive)
    {
        try { return new ZipArchive(archive, ZipArchiveMode.Read, leaveOpen: true); }
        catch (InvalidDataException) { return null; }
    }

    /// <summary>Returns a canonical relative path, or null when the entry name is unusable or unsafe.</summary>
    private static string? Normalize(string name, int maximumPathDepth)
    {
        if (string.IsNullOrWhiteSpace(name) || name.Any(char.IsControl)) return null;
        var normalized = name.Replace('\\', '/').TrimEnd('/');
        if (normalized.Length == 0) return string.Empty;
        if (normalized.StartsWith('/') || normalized.Length >= 2 && normalized[1] == ':') return null;
        var segments = normalized.Split('/', StringSplitOptions.RemoveEmptyEntries);
        if (segments.Length > maximumPathDepth) return null;
        if (segments.Any(segment => segment is "." or "..")) return null;
        return string.Join('/', segments);
    }

    /// <summary>
    /// Detects a symbolic-link entry through the stored Unix mode bits. The server materializes file
    /// contents itself, so a link can never become a real link; rejecting it keeps the build context
    /// free of entries that only pretend to be files.
    /// </summary>
    private static bool IsLink(ZipArchiveEntry entry) => ((entry.ExternalAttributes >> 16) & 0xF000) == 0xA000;
}
